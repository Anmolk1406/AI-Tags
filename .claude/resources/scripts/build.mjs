#!/usr/bin/env node
// Regenerates the generated resources:  npm run resources:build
//   screens.md                  from the live registry (src/flows/index.ts)
//   flows/categories-views.md   every view the Categories tab links to (src/flows/categories/data.live.ts +
//                               linkRouting.ts, plus cms-pages.json once `npm run categories:fetch` has run)
//   --check   exit 1 if either is out of date (run by npm run skill:check)
//
// screens.md is the "where is everything" index the skills read before touching a flow: every route with its
// URL, presentation, source of truth, verified date and source, plus each flow's files (mapping docs, variant
// data / token files, stores, flow-local components). Never edit it by hand.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../..');
const out = join(here, '../screens.md');
const check = process.argv.includes('--check');

const { createServer } = await import(join(root, 'node_modules/vite/dist/node/index.js'));
const vite = await createServer({ root, configFile: false, logLevel: 'error', server: { middlewareMode: true }, appType: 'custom', assetsInclude: ['**/*.lottie'], resolve: { alias: { '@assets': join(root, 'src/assets') } } });
let allFlows, screenTruth, pageAliases, liveCategoriesPage, destinationOf, guessPageType;
try {
  ({ liveCategoriesPage } = await vite.ssrLoadModule('/src/flows/categories/data.live.ts'));
  ({ destinationOf, guessPageType } = await vite.ssrLoadModule('/src/flows/categories/linkRouting.ts'));
  ({ allFlows } = await vite.ssrLoadModule('/src/flows/index.ts'));
  ({ screenTruth } = await vite.ssrLoadModule('/src/kit/registry.ts'));
  ({ pageAliases } = await vite.ssrLoadModule('/src/kit/routes.ts'));
} finally {
  await vite.close();
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const short = (s, n = 110) => (s && s.length > n ? `${s.slice(0, n - 1)}…` : s ?? '');
const aliasesOf = (route) => Object.entries(pageAliases).filter(([, r]) => r === route).map(([a]) => `/${a}`);

function flowFiles(id) {
  const dir = join(root, 'src/flows', id);
  if (!existsSync(dir)) return {};
  const files = readdirSync(dir);
  const comps = existsSync(join(dir, 'components'))
    ? readdirSync(join(dir, 'components'), { recursive: true }).filter((f) => /\.tsx$/.test(f)).map((f) => f.replace(/\.tsx$/, ''))
    : [];
  return {
    docs: files.filter((f) => /\.md$/.test(f)),
    variants: files.filter((f) => /^(data|tokens)\.[\w-]+\.ts$/.test(f)),
    state: files.filter((f) => /^(store|motion|assets|scrollStates)\.ts$/.test(f)),
    comps,
  };
}

const truthTotals = {};
let lines = [
  '# Screen index (generated)',
  '',
  '<!-- Generated by .claude/resources/scripts/build.mjs from src/flows/index.ts. Do not edit; run `npm run resources:build`. -->',
  '',
  `${allFlows.length} flows · ${allFlows.reduce((n, f) => n + f.screens.length, 0)} routes. Truth: which reference wins for that screen (\`bappzaar\` master, \`figma\` frame, \`mixed\` = Figma look + bappzaar behaviour per the flow's mapping doc, \`reference\` = user-shared). Open the flow brief in \`flows/\` for how the pieces fit.`,
  '',
];
for (const f of allFlows) {
  const ff = flowFiles(f.id);
  lines.push(`## ${f.id} · ${cell(f.title)}`, '');
  const meta = [`initial \`${f.id}/${f.initial}\``];
  if (f.group) meta.push(`group ${f.group}`);
  if (f.parent) meta.push(`parent \`${f.parent}\``);
  if (f.sheetBackdrop) meta.push(`sheetBackdrop \`${f.sheetBackdrop}\``);
  if (f.tabBar) meta.push(`tab \`${f.tabBar.tab}\` on ${f.tabBar.screens.map((s) => `\`${s}\``).join(', ')}`);
  lines.push(meta.join(' · '), '');
  const extras = [];
  if (ff.docs?.length) extras.push(`docs: ${ff.docs.map((d) => `\`src/flows/${f.id}/${d}\``).join(', ')}`);
  if (ff.variants?.length) extras.push(`data / token files: ${ff.variants.map((d) => `\`${d}\``).join(', ')}`);
  if (ff.state?.length) extras.push(`state / helpers: ${ff.state.map((d) => `\`${d}\``).join(', ')}`);
  if (ff.comps?.length) extras.push(`components/: ${ff.comps.join(', ')}`);
  for (const e of extras) lines.push(`- ${e}`);
  if (extras.length) lines.push('');
  lines.push('| Route | Title | Presentation | URL | Truth | Verified | Source |', '|---|---|---|---|---|---|---|');
  for (const s of f.screens) {
    const route = `${f.id}/${s.id}`;
    const truth = screenTruth(s);
    truthTotals[truth] = (truthTotals[truth] ?? 0) + 1;
    const urls = [...new Set([...aliasesOf(route), ...[s.path ?? []].flat().map((p) => `/${p}`)])].join(' ');
    lines.push(`| \`${route}\` | ${cell(s.title)} | ${s.presentation ?? 'screen'} | ${cell(urls)} | ${truth}${s.truth ? '' : '*'} | ${s.verified ?? ''} | ${cell(short(s.source))} |`);
  }
  lines.push('');
}
lines.push(`Totals by truth: ${Object.entries(truthTotals).map(([k, v]) => `${v} ${k}`).join(' · ')}. \`*\` = inferred from \`source\` (no explicit \`truth\`).`, '');
const md = lines.join('\n');

// ── flows/categories-views.md
const cmsFile = join(root, 'src/flows/categories/cms-pages.json');
const cms = existsSync(cmsFile) ? JSON.parse(readFileSync(cmsFile, 'utf8')) : null;
const destLabel = (d) =>
  d.kind === 'dynamicLoader' ? (d.product ? 'PDP (DynamicLoaderBlankHeader)' : 'DynamicLoaderScreen') : d.kind === 'giftCards' ? `${d.screen.replace('noon.', '')}${d.categoryCode ? ` \`${d.categoryCode}\`` : ''}` : d.screen ? d.screen.replace('noon.', '') : d.kind;
function pageCell(url) {
  const d = destinationOf(url);
  if (d.kind !== 'dynamicLoader') return ['—', '—'];
  const p = cms?.pages?.[url];
  if (!p) return [`${guessPageType(url)}?`, '—'];
  if (p.error || (p.status && p.status >= 400)) return [`error ${p.status ?? ''}`.trim(), cell(p.error ?? '')];
  const mods = (list) => list.map((m) => `${m.type}${m.count != null ? `×${m.count}` : ''}`).join(', ');
  if (p.type === 'static') return [`static${p.store ? ' (store)' : ''}`, cell(mods(p.modules ?? [])) || 'no modules'];
  if (p.type === 'catalog') {
    const parts = [];
    if (p.hits != null) parts.push(`${p.hits} hits`);
    if (p.navPills?.length) parts.push(`pills: ${p.navPills.slice(0, 6).join(', ')}${p.navPills.length > 6 ? '…' : ''}`);
    if (p.quickFilters) parts.push(`${p.quickFilters} quick filters`);
    if (p.cms?.length) parts.push(`cms: ${mods(p.cms)}`);
    if (p.bestSeller) parts.push('best-seller page');
    return ['catalog', cell(parts.join(' · ')) || '—'];
  }
  return [p.type ?? '?', '—'];
}
const cv = [
  '# Categories tab: every view it links to (generated)',
  '',
  '<!-- Generated by .claude/resources/scripts/build.mjs. Do not edit; run `npm run resources:build` (after `npm run categories:fetch` for live page types). -->',
  '',
  cms
    ? `Page types and sections: live fetch of ${cms.fetchedAt} (${cms.locale}), \`src/flows/categories/cms-pages.json\`.`
    : 'Page types are **guesses** from the URL (`guessPageType`, marked `?`): the live pages have not been fetched yet. Run `npm run categories:fetch`, then `npm run resources:build`, to fill in each page\'s real type and sections.',
  '',
  'Tap routing follows bappzaar `ModuleHelper.handlePress` (`src/flows/categories/linkRouting.ts`): a main tile only expands its sub-list; a sub banner opens its `linkUrl`. See `categories.md` for what each destination renders.',
  '',
];
const all = liveCategoriesPage.banners.flatMap((b) => b.subBanners.map((s) => s.linkUrl));
const kinds = {};
for (const u of new Set(all)) {
  const d = destinationOf(u);
  const k = d.kind === 'dynamicLoader' ? (cms?.pages?.[u]?.type ?? `${guessPageType(u)}?`) : (d.screen ?? d.kind).replace('noon.', '');
  kinds[k] = (kinds[k] ?? 0) + 1;
}
cv.push(`${liveCategoriesPage.banners.length} category tiles · ${all.length} sub banners · ${new Set(all).size} unique links. By destination: ${Object.entries(kinds).map(([k, v]) => `${v} ${k}`).join(' · ')}.`, '');
const ad = liveCategoriesPage.adBanner;
cv.push('## Pre-search banner', '', '| Link | Opens | Page | Sections |', '|---|---|---|---|', `| \`${ad.linkUrl}\` | ${destLabel(destinationOf(ad.linkUrl))} | ${pageCell(ad.linkUrl).join(' | ')} |`, '');
for (const b of liveCategoriesPage.banners) {
  cv.push(`## ${b.title}`, '', `Tile \`${b.image}\` · label \`${b.label ?? 'null'}\` · \`?open=${b.image.replace(/^cat-/, '')}\``, '', '| Sub banner | Link | Opens | Page | Sections |', '|---|---|---|---|---|');
  for (const sb of b.subBanners) cv.push(`| ${cell(sb.title)} | \`${sb.linkUrl}\` | ${destLabel(destinationOf(sb.linkUrl))} | ${pageCell(sb.linkUrl).join(' | ')} |`);
  cv.push('');
}
const outputs = [
  [out, md],
  [join(here, '../flows/categories-views.md'), cv.join('\n')],
];

if (check) {
  const stale = outputs.filter(([f, text]) => (existsSync(f) ? readFileSync(f, 'utf8') : '') !== text).map(([f]) => f.replace(root + '/', ''));
  if (stale.length) {
    console.log(`✗ out of date: ${stale.join(', ')}: run npm run resources:build`);
    process.exit(1);
  }
  console.log('✓ generated resources are current');
} else {
  for (const [f, text] of outputs) {
    writeFileSync(f, text);
    console.log(`wrote ${f.replace(root + '/', '')}`);
  }
}
